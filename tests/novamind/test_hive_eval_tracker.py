def test_record_eval_success():
    et.record_eval(
        agent_id="coder-01",
        agent_type="coder",
        precision=0.95,
        confidence=0.88,
        duration_ms=1200,
        success=True,
    )
    total = et.get_total_evals()
    assert total["evals"] == 1
    assert total["failures"] == 0
    assert total["avg_precision"] > 0.9


def test_record_eval_failure():
    et.record_eval(
        agent_id="coder-01",
        agent_type="coder",
        success=False,
        notes="timeout on provider",
    )
    total = et.get_total_evals()
    assert total["evals"] == 1
    assert total["failures"] == 1


def test_agent_stats():
    et.record_eval(agent_id="coder-01", precision=0.9, confidence=0.9)
    et.record_eval(agent_id="coder-01", precision=0.8, confidence=0.7)
    et.record_eval(agent_id="reviewer-01", agent_type="reviewer", precision=1.0)

    stats = et.get_agent_stats()
    assert len(stats) == 2

    coder = next(s for s in stats if s["agent_id"] == "coder-01")
    assert coder["evals"] == 2
    assert abs(coder["avg_precision"] - 0.85) < 0.01


def test_task_id_autogenerated():
    """task_id افتراضي عند عدم توفره (NOT NULL)."""
    et.record_eval(agent_id="x")
    import sqlite3
    con = sqlite3.connect(str(et.DB_PATH))
    row = con.execute("SELECT task_id FROM evaluations ORDER BY id DESC LIMIT 1").fetchone()
    con.close()
    assert row[0]  # not None or empty
    assert row[0].startswith("anon-")


def test_notes_default_empty():
    """notes يقبل None ويصبح ''."""
    et.record_eval(agent_id="x", notes=None)
    import sqlite3
    con = sqlite3.connect(str(et.DB_PATH))
    row = con.execute("SELECT notes FROM evaluations ORDER BY id DESC LIMIT 1").fetchone()
    con.close()
    assert row[0] == "" or row[0] is not None


