"""TechnicalWriter — توثيق تقني احترافي."""
from novamind.base import BaseAgent
from pathlib import Path
from datetime import datetime
import logging

log = logging.getLogger("TechnicalWriter")


class TechnicalWriter(BaseAgent):
    NAME = "techwriter"
    DESCRIPTION = "يكتب توثيقاً تقنياً احترافياً"
    ROLE = "researcher"
    LEVEL = 3
    CAPABILITIES = [
        "write_docs", "write_tutorials", "write_api_docs",
        "create_diagrams", "write_changelog", "maintain_wiki",
        "write_readme", "generate_toc", "techwriter",
    ]

    def _register_tools(self):
        self.tools = {
            "write_file": self._write_file,
            "generate_toc": self._generate_toc,
        }

    async def handle(self, task):
        action = task.get("action", "").lower()
        params = task.get("params", {})
        try:
            if "readme" in action:
                return self._write_readme(params)
            if "changelog" in action:
                return self._write_changelog(params)
            if "toc" in action:
                return self._generate_toc(params)
            if "tutorial" in action:
                return self._write_tutorial(params)
            if "api" in action or "docs" in action:
                return self._write_docs(params)
            if "write" in action:
                return self._write_file(params)
            return {"ok": True, "result": "TechWriter: " + action}
        except Exception as e:
            log.exception("TechnicalWriter failed")
            return {"ok": False, "error": type(e).__name__ + ": " + str(e)}

    def _write_file(self, params):
        path = params.get("path")
        content = params.get("content", "")
        if not path:
            return {"ok": False, "error": "no path"}
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        return {"ok": True, "result": "written: " + path}

    def _write_readme(self, params):
        name = params.get("name", "Project")
        desc = params.get("description", "")
        path = params.get("path", "/public/docs/" + name + "/README.md")
        content = "# " + name + "\n\n" + desc + "\n\nGenerated by HIVE.\n"
        return self._write_file({"path": path, "content": content})

    def _write_changelog(self, params):
        entries = params.get("entries", [])
        path = params.get("path", "/public/CHANGELOG.md")
        lines = ["# Changelog", ""]
        for entry in entries:
            date = entry.get("date", datetime.now().strftime("%Y-%m-%d"))
            title = entry.get("title", "Changes")
            items = entry.get("items", [])
            lines.append("## [" + date + "] - " + title)
            lines.append("")
            for item in items:
                lines.append("- " + item)
            lines.append("")
        Path(path).write_text("\n".join(lines))
        return {"ok": True, "result": "changelog updated"}

    def _generate_toc(self, params):
        text = params.get("text", "")
        if not text and params.get("path"):
            text = Path(params["path"]).read_text()
        toc = []
        for line in text.split("\n"):
            if line.startswith("#"):
                level = len(line) - len(line.lstrip("#"))
                title = line.lstrip("#").strip()
                toc.append({"level": level, "title": title})
        return {"ok": True, "result": {"toc": toc, "count": len(toc)}}

    def _write_tutorial(self, params):
        topic = params.get("topic", "Tutorial")
        slug = topic.lower().replace(" ", "_")
        path = params.get("path", "/public/docs/tutorials/" + slug + ".md")
        content = "# Tutorial: " + topic + "\n\nGenerated by HIVE.\n"
        return self._write_file({"path": path, "content": content})

    def _write_docs(self, params):
        module = params.get("module", "module")
        path = params.get("path", "/public/docs/api/" + module + ".md")
        content = "# API: " + module + "\n\nGenerated by HIVE.\n"
        return self._write_file({"path": path, "content": content})

# Auto-instance for registry
technical_writer = TechnicalWriter()
